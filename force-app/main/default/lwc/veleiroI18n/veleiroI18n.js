// Sustituye {0}, {1}… Sin dependencias: Intl no formatea plantillas.
export function fmt(template, values) {
    if (!template) return '';
    return (values || []).reduce(
        (out, v, i) => out.split(`{${i}}`).join(v === null || v === undefined ? '' : String(v)),
        template
    );
}
